local function hl_name(key) return "StackableLogo" .. key end

local function logo_lines()
  local lines = {}
  for _, segs in ipairs(logo) do
    local text = {}
    for _, seg in ipairs(segs) do
      text[#text + 1] = { seg[1], hl = seg[2] and hl_name(seg[2]) or nil }
    end
    lines[#lines + 1] = { text = text, align = "center" }
  end
  return lines
end

---@type LazySpec
return {
  "folke/snacks.nvim",
  opts = function(_, opts)
    local function define_highlights()
      for key, color in pairs(colors) do
        vim.api.nvim_set_hl(0, hl_name(key), { fg = color })
      end
    end
    define_highlights()
    vim.api.nvim_create_autocmd("ColorScheme", { callback = define_highlights })

    opts.dashboard = opts.dashboard or {}
    opts.dashboard.sections = {
      logo_lines,
      { padding = 3 },
      { section = "keys", gap = 1, padding = 3 },
      { section = "startup" },
    }
  end,
}
